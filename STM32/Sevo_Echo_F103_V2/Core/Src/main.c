char * float_to_string(float value, char* buffer, int16_t precision) {
  int32_t fixed_value;
  int32_t float_value;
  int8_t negative = 0;

  // 处理负数
  if(value < 0) {
    negative = 1;
    value = -value; 
  }

  switch(precision) {
    case 1:
      fixed_value = (int32_t)(value);
      // 修正浮点运算精度问题
      float_value = (int32_t)((value - fixed_value) * 10.0f + 0.5f);
      if(negative && (fixed_value != 0 || float_value != 0)) {
        sprintf(buffer, "-%d.%d", fixed_value, float_value);
      } else {
        sprintf(buffer, "%d.%d", fixed_value, float_value);
      }
      return buffer;
    case 2:
      fixed_value = (int32_t)(value);
      // 修正浮点运算精度问题
      float_value = (int32_t)((value - fixed_value) * 100.0f + 0.5f);
      if(negative && (fixed_value != 0 || float_value != 0)) {
        sprintf(buffer, "-%d.%02d", fixed_value, float_value);
      } else {
        sprintf(buffer, "%d.%02d", fixed_value, float_value);
      }
      return buffer;
    default:
      fixed_value = (int32_t)(value + 0.5f);
      float_value = 0;
      if(negative && fixed_value != 0) {
        sprintf(buffer, "-%d", fixed_value);
      } else {
        sprintf(buffer, "%d", fixed_value);
      }
      return buffer;
  }
}
