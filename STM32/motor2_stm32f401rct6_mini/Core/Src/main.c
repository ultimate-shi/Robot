void process_usb() {
    if(_cmd_buffer_len > 0) {
      process_command((char*)_cmd_buffer, _cmd_buffer_len);
      memset((void*)_cmd_buffer, 0, sizeof(_cmd_buffer));
      _cmd_buffer_len = 0;
    }
#ifdef _PRINTF_
    osDelay(1);
    xSemaphoreTake(_usb_mutex, portMAX_DELAY);
    if(_usb_connected && _stdout_rdy) {
      if(CDC_Transmit_FS((uint8_t*)_stdout_buffer, _stdout_ptr) != USBD_BUSY) {
        _stdout_ptr = 0;
        _stdout_rdy = 0;
      }
    }
    xSemaphoreGive(_usb_mutex);
#endif
}
