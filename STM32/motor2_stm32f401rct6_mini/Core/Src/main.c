//模拟USB插拔
void unplug_plug_usb() {
  __HAL_RCC_GPIOA_CLK_ENABLE();
  GPIO_InitTypeDef GPIO_InitStruct = {0};
  /*Configure GPIO pin Output Level */
  HAL_GPIO_WritePin(GPIOA, GPIO_PIN_12, GPIO_PIN_RESET);
  /*Configure GPIO pin : PA12 */
  GPIO_InitStruct.Pin = GPIO_PIN_12;
  GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
  GPIO_InitStruct.Pull = GPIO_PULLDOWN;
  GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_LOW;
  HAL_GPIO_Init(GPIOA, &GPIO_InitStruct);

  HAL_GPIO_WritePin(GPIOA, GPIO_PIN_12,
  GPIO_PIN_RESET);
  HAL_Delay(65);
  //先把PA12拉低再拉高，利用D+模拟USB的拔插动作
  HAL_GPIO_WritePin(GPIOA,GPIO_PIN_12,GPIO_PIN_SET);
  HAL_Delay(65);
}

char * float_to_string(float value, char* buffer, int16_t precision) {
  int32_t fixed_value;
  int32_t float_value;
  int8_t negative = 0;

  // 处理负数
  if(value < 0) {
    negative = 1;
    value = -value;
  }

  switch(precision) {
    case 1:
      fixed_value = (int32_t)(value);
      // 修正浮点运算精度问题
      float_value = (int32_t)((value - fixed_value) * 10.0f + 0.5f);
      if(negative && (fixed_value != 0 || float_value != 0)) {
        sprintf(buffer, "-%ld.%ld", fixed_value, float_value);
      } else {
        sprintf(buffer, "%ld.%ld", fixed_value, float_value);
      }
      return buffer;
    case 2:
      fixed_value = (int32_t)(value);
      // 修正浮点运算精度问题
      float_value = (int32_t)((value - fixed_value) * 100.0f + 0.5f);
      if(negative && (fixed_value != 0 || float_value != 0)) {
        sprintf(buffer, "-%ld.%02ld", fixed_value, float_value);
      } else {
        sprintf(buffer, "%ld.%02ld", fixed_value, float_value);
      }
      return buffer;
    default:
      fixed_value = (int32_t)(value + 0.5f);
      float_value = 0;
      if(negative && fixed_value != 0) {
        sprintf(buffer, "-%ld", fixed_value);
      } else {
        sprintf(buffer, "%ld", fixed_value);
      }
      return buffer;
  }
}

